#!/usr/bin/env node
/* Build the client-side search index for the Learning Hub.
   Output: assets/js/search-index.js  (window.LICHUB_INDEX = [...])
   Run from the repository root:  node tools/build-search-index.mjs
   No dependencies. The index is a plain JS file (not fetched JSON) so search
   also works when the site is opened over file:// . */
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');

const strip = (h) => h
  .replace(/<script[\s\S]*?<\/script>/gi, ' ')
  .replace(/<style[\s\S]*?<\/style>/gi, ' ')
  .replace(/<[^>]+>/g, ' ')
  .replace(/&nbsp;/g, ' ').replace(/&amp;/g, '&').replace(/&lt;/g, '<')
  .replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&#39;/g, "'")
  .replace(/\s+/g, ' ').trim();

const fold = (s) => s.toLowerCase().normalize('NFD')
  .replace(/[̀-ͯ]/g, '').replace(/đ/g, 'd');

function headings(html, max = 44) {
  const out = [];
  const re = /<(h[123]|summary)[^>]*>([\s\S]*?)<\/\1>/gi;
  let m;
  while ((m = re.exec(html)) && out.length < max) {
    const t = strip(m[2]);
    if (t && t.length > 2 && t.length < 140 && !out.includes(t)) out.push(t);
  }
  return out;
}

function entry(v, file, week, forcedTitle) {
  const p = `versions/${v}/${file}`;
  const html = fs.readFileSync(path.join(ROOT, p), 'utf8');
  const tTag = (html.match(/<title>([\s\S]*?)<\/title>/i) || [])[1];
  const h1 = (html.match(/<h1[^>]*>([\s\S]*?)<\/h1>/i) || [])[1];
  const t = forcedTitle || strip(h1 || tTag || file).slice(0, 110);
  const h = headings(html);
  return { v, w: week, t, p, h, ft: fold(t), fh: fold(h.join(' § ')) };
}

const IDX = [];
// V1 — 11 historical week pages (Week5 missing by history; its notice page is not curriculum content)
for (const w of [1, 2, 3, 4, 6, 7, 8, 9, 10, 11, 12]) IDX.push(entry('v1', `Week${w}.html`, w));
// V2 — 12 week pages
for (let w = 1; w <= 12; w++) IDX.push(entry('v2', `Week${w}.html`, w));
// V3 — 12 week pages + docs
for (let w = 1; w <= 12; w++) {
  const f = `Week${String(w).padStart(2, '0')}.html`;
  IDX.push(entry('v3', f, w));
}
for (const f of ['index.html', 'README.html', 'CURRICULUM_MAP.html', 'MENTOR_GUIDE.html',
  'PROJECT_GUIDE.html', 'TECHNICAL_AUDIT.html', 'VALIDATION_REPORT.html',
  'CHANGELOG_V2_TO_V3.html', 'implementation-notes.html']) {
  IDX.push(entry('v3', f, null));
}

const js = '/* Generated by tools/build-search-index.mjs — do not edit by hand. */\n'
  + 'window.LICHUB_INDEX = ' + JSON.stringify(IDX) + ';\n';
fs.writeFileSync(path.join(ROOT, 'assets/js/search-index.js'), js);
console.log(`search index: ${IDX.length} entries, ${(js.length / 1024).toFixed(1)} KB`);
